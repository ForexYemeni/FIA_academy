const q = (text) => pool.query(text)
const lit = (v) => {
  if (v === null || v === undefined) return 'NULL'
  if (typeof v === 'number') return isFinite(v) ? String(v) : 'NULL'
  if (typeof v === 'boolean') return v ? 'true' : 'false'
  if (v instanceof Date) return `'${v.toISOString()}'`
  if (typeof v === 'object') return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`
  return `'${String(v).replace(/'/g, "''")}'`
}

async function main() {
  const tablesRes = await q(`
    SELECT c.relname AS name, c.reltuples::bigint AS est
    FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname='public' AND c.relkind='r'
    ORDER BY c.relname`)
  const tables = tablesRes.rows.map(r => r.name)
  console.log('Tables:', tables.length)

  // ---- Schema DDL ----
  let ddl = `-- FIA Academy DB Schema Backup ${new Date().toISOString()}\n-- Generated by backup-db.mjs\n\n`
  for (const t of tables) {
    const cols = await q(`
      SELECT column_name, data_type, character_maximum_length, numeric_precision,
             numeric_scale, is_nullable, column_default
      FROM information_schema.columns WHERE table_schema='public' AND table_name='${t}'
      ORDER BY ordinal_position`)
    ddl += `CREATE TABLE IF NOT EXISTS public."${t}" (\n`
    ddl += cols.rows.map(c => {
      let type = c.data_type
      if (type === 'character varying') type = `varchar(${c.character_maximum_length || 255})`
      if (type === 'numeric') type = `numeric(${c.numeric_precision || 10},${c.numeric_scale || 0})`
      if (type === 'timestamp with time zone') type = 'timestamptz'
      if (type === 'timestamp without time zone') type = 'timestamp'
      const nn = c.is_nullable === 'NO' ? ' NOT NULL' : ''
      const def = c.column_default ? ` DEFAULT ${c.column_default}` : ''
      return `  "${c.column_name}" ${type}${nn}${def}`
    }).join(',\n')
    const pk = await q(`
      SELECT a.attname FROM pg_index i
      JOIN pg_attribute a ON a.attrelid = i.indrelid AND a.attnum = ANY(i.indkey)
      WHERE i.indrelid = 'public."${t}"'::regclass AND i.indisprimary`)
    if (pk.rows.length) ddl += `,\n  PRIMARY KEY (${pk.rows.map(r => `"${r.attname}"`).join(', ')})`
    ddl += `\n);\n\n`
  }
  const idx = await q(`SELECT indexname, indexdef FROM pg_indexes WHERE schemaname='public' AND indexname NOT LIKE '%_pkey'`)
  for (const r of idx.rows) ddl += `${r.indexdef};\n`
  fs.writeFileSync(`${OUT_DIR}/schema.sql`, ddl)
  console.log('schema.sql written:', (ddl.length / 1024).toFixed(1), 'KB')

  // ---- Data INSERTs + JSON ----
  let sql = `-- FIA Academy DB Data Backup ${new Date().toISOString()}\nBEGIN;\n`
  const jsonAll = {}
  let totalRows = 0
  for (const t of tables) {
    const res = await q(`SELECT * FROM public."${t}"`)
    jsonAll[t] = res.rows
    totalRows += res.rows.length
    if (res.rows.length) {
      const colNames = res.fields.map(f => `"${f.name}"`).join(', ')
      sql += `\n-- Table: ${t} (${res.rows.length} rows)\n`
      for (const row of res.rows) {
        sql += `INSERT INTO public."${t}" (${colNames}) VALUES (${res.fields.map(f => lit(row[f.name])).join(', ')});\n`
      }
    }
  }
  sql += `\nCOMMIT;\n`
  fs.writeFileSync(`${OUT_DIR}/data.sql`, sql)
  fs.writeFileSync(`${OUT_DIR}/data.json`, JSON.stringify(jsonAll, null, 1))
  console.log('data.sql written:', (sql.length / 1024 / 1024).toFixed(2), 'MB —', totalRows, 'total rows')
  const summary = tables.map(t => `${t}: ${jsonAll[t].length}`).join(', ')
  console.log('Rows per table:', summary)
  await pool.end()
}

main().catch(e => { console.error('BACKUP FAILED:', e.message); process.exit(1) })
