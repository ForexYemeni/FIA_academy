#!/usr/bin/env python3
"""
FIA Academy — Certificate PNG Preview Generator (high-res)
Uses matplotlib to render a beautiful certificate as PNG for on-screen preview.
The authoritative PDF version is generated by generate_certificate.py.
"""
import sys
import os
import io
import qrcode
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import matplotlib.patches as patches
from matplotlib.patches import FancyBboxPatch, Circle, Rectangle, FancyArrowPatch
from matplotlib.font_manager import FontProperties
import numpy as np
import math

NAVY = '#0B1635'
NAVY_LIGHT = '#1A2547'
GOLD = '#D4AF37'
GOLD_LIGHT = '#E5C158'
CREAM = '#FBF7EE'
GRAY = '#666666'

# Try Arabic shaping
def shape_ar(text):
    try:
        import arabic_reshaper
        from bidi.algorithm import get_display
        return get_display(arabic_reshaper.reshape(text))
    except Exception:
        return text[::-1] if text else text

# Load Cairo font
CAIRO_PATH = '/home/z/my-project/.fonts/Cairo-Regular.ttf'
CAIRO_BOLD_PATH = '/home/z/my-project/.fonts/Cairo-Bold.ttf'
font_regular = FontProperties(fname=CAIRO_PATH) if os.path.exists(CAIRO_PATH) else FontProperties()
font_bold = FontProperties(fname=CAIRO_BOLD_PATH) if os.path.exists(CAIRO_BOLD_PATH) else FontProperties(weight='bold')


def generate_certificate_png(
    student_name: str,
    course_title: str,
    certificate_number: str,
    issue_date: str,
    issued_by: str = 'أكاديمية المستقبل الدولية',
    output_path: str = None,
    verify_url: str = None,
) -> bytes:
    fig, ax = plt.subplots(figsize=(14, 10), dpi=150)
    ax.set_xlim(0, 14)
    ax.set_ylim(0, 10)
    ax.set_aspect('equal')
    ax.axis('off')
    fig.patch.set_facecolor(CREAM)
    ax.set_facecolor(CREAM)

    # Outer navy border
    border = Rectangle((0.2, 0.2), 13.6, 9.6, linewidth=15, edgecolor=NAVY, facecolor='none')
    ax.add_patch(border)
    # Inner gold border
    inner = Rectangle((0.4, 0.4), 13.2, 9.2, linewidth=2, edgecolor=GOLD, facecolor='none')
    ax.add_patch(inner)
    # Corner ornaments
    for (x, y) in [(0.4, 0.4), (13.2, 0.4), (0.4, 9.2), (13.2, 9.2)]:
        ax.add_patch(Rectangle((x, y), 0.2, 0.2, facecolor=GOLD, edgecolor='none'))

    # ===== Header: Logo circle + Academy name =====
    cx = 7  # center x
    # Navy circle with gold ring
    ax.add_patch(Circle((cx, 8.5), 0.55, facecolor=NAVY, edgecolor=GOLD, linewidth=3))
    ax.text(cx, 8.42, 'FIA', ha='center', va='center', color=GOLD, fontsize=18, fontproperties=font_bold)

    # Academy name
    ax.text(cx, 7.7, shape_ar(issued_by), ha='center', va='center', color=NAVY, fontsize=24, fontproperties=font_bold)
    ax.text(cx, 7.3, 'FUTURE INTERNATIONAL ACADEMY', ha='center', va='center', color=GOLD, fontsize=9, fontproperties=font_bold)

    # Decorative gold line
    ax.plot([cx-2.5, cx+2.5], [7.1, 7.1], color=GOLD, linewidth=1)

    # ===== Body =====
    ax.text(cx, 6.5, shape_ar('شهادة إتمام دورة معتمدة'), ha='center', va='center', color=NAVY, fontsize=14, fontproperties=font_regular)
    ax.text(cx, 6.15, shape_ar('تشهد أكاديمية المستقبل الدولية بأن'), ha='center', va='center', color=GRAY, fontsize=10, fontproperties=font_regular)

    # Student name — large gold
    ax.text(cx, 5.4, student_name, ha='center', va='center', color=GOLD, fontsize=30, fontproperties=font_bold)
    # Underline
    name_w = len(student_name) * 0.18
    ax.plot([cx-name_w/2-0.3, cx+name_w/2+0.3], [5.0, 5.0], color=GOLD, linewidth=1)

    ax.text(cx, 4.65, shape_ar('قد أتم بنجاح متطلبات دورة'), ha='center', va='center', color=GRAY, fontsize=10, fontproperties=font_regular)
    ax.text(cx, 4.1, shape_ar(course_title), ha='center', va='center', color=NAVY, fontsize=15, fontproperties=font_bold)

    # ===== Footer =====
    # Left: Date
    ax.text(2.5, 1.8, shape_ar('تاريخ الإصدار'), ha='center', va='center', color=GRAY, fontsize=9, fontproperties=font_regular)
    ax.text(2.5, 1.5, issue_date, ha='center', va='center', color=NAVY, fontsize=11, fontproperties=font_bold)

    # Center: Barcode (visual lines)
    barcode_w = 4
    barcode_x = cx - barcode_w / 2
    barcode_y = 1.4
    # Generate pseudo-barcode stripes
    np.random.seed(hash(certificate_number) & 0xFFFFFFFF)
    n_stripes = 40
    stripe_positions = np.sort(np.random.uniform(barcode_x, barcode_x + barcode_w, n_stripes))
    last_x = barcode_x
    for i, sx in enumerate(stripe_positions):
        w = np.random.uniform(0.02, 0.06)
        if i % 2 == 0:
            ax.add_patch(Rectangle((sx, barcode_y), w, 0.5, facecolor=NAVY, edgecolor='none'))
    # Barcode caption
    ax.text(cx, 1.15, certificate_number, ha='center', va='center', color=NAVY, fontsize=10, fontproperties=font_bold)

    # Right: Signature
    ax.text(11.5, 2.0, shape_ar('توقيع الجهة المانوحة'), ha='center', va='center', color=GRAY, fontsize=9, fontproperties=font_regular)
    ax.plot([10.5, 12.5], [1.85, 1.85], color=NAVY, linewidth=1)
    ax.text(11.5, 1.5, shape_ar('المدير التنفيذي'), ha='center', va='center', color=NAVY, fontsize=11, fontproperties=font_bold)

    # ===== Gold seal (right of signature) =====
    seal_x, seal_y, seal_r = 12.3, 2.6, 0.5
    ax.add_patch(Circle((seal_x, seal_y), seal_r, facecolor='white', edgecolor=GOLD, linewidth=3))
    ax.add_patch(Circle((seal_x, seal_y), seal_r-0.08, facecolor='none', edgecolor=NAVY, linewidth=1))
    ax.text(seal_x, seal_y+0.07, 'FIA', ha='center', va='center', color=NAVY, fontsize=10, fontproperties=font_bold)
    ax.text(seal_x, seal_y-0.15, shape_ar('معتمد'), ha='center', va='center', color=NAVY, fontsize=7, fontproperties=font_bold)
    # 8 gold stars around
    for i in range(8):
        a = i * math.pi / 4
        sx = seal_x + math.cos(a) * (seal_r + 0.07)
        sy = seal_y + math.sin(a) * (seal_r + 0.07)
        ax.add_patch(Circle((sx, sy), 0.025, facecolor=GOLD, edgecolor='none'))

    # ===== QR code (left, near date) =====
    qr_url = verify_url or f'https://fia.edu/verify?number={certificate_number}'
    qr = qrcode.QRCode(version=1, box_size=4, border=1)
    qr.add_data(qr_url)
    qr.make(fit=True)
    qr_img = qr.make_image(fill_color=NAVY, back_color=CREAM).convert('RGB')
    qr_arr = np.array(qr_img) / 255.0
    qr_extent = [2.15, 2.85, 2.05, 2.75]  # [x0, x1, y0, y1]
    ax.imshow(qr_arr, extent=qr_extent, cmap='gray', aspect='equal')
    ax.text(2.5, 1.95, shape_ar('امسح للتحقق'), ha='center', va='center', color=GRAY, fontsize=7, fontproperties=font_regular)

    # Gold ribbon at bottom
    ax.add_patch(Rectangle((1.0, 0.6), 12, 0.13, facecolor=GOLD, edgecolor='none'))

    # Verify URL at very bottom
    ax.text(cx, 0.42, f'{shape_ar("للتحقق:")} {qr_url}', ha='center', va='center', color=GRAY, fontsize=8, fontproperties=font_regular)

    # Watermark (very faint FIA diagonal)
    ax.text(cx, 5, 'FIA', ha='center', va='center', color=NAVY, fontsize=120, fontproperties=font_bold, alpha=0.05, rotation=45)

    plt.tight_layout(pad=0)
    buf = io.BytesIO()
    plt.savefig(buf, format='png', dpi=150, facecolor=CREAM, bbox_inches='tight', pad_inches=0.1)
    plt.close(fig)
    buf.seek(0)
    png_bytes = buf.getvalue()
    if output_path:
        with open(output_path, 'wb') as f:
            f.write(png_bytes)
        return None
    return png_bytes


if __name__ == '__main__':
    if len(sys.argv) < 5:
        print('Usage: generate_certificate_png.py <student_name> <course_title> <cert_number> <issue_date> [output_path] [verify_url]')
        sys.exit(1)
    student = sys.argv[1]
    course = sys.argv[2]
    num = sys.argv[3]
    date = sys.argv[4]
    out = sys.argv[5] if len(sys.argv) > 5 else None
    url = sys.argv[6] if len(sys.argv) > 6 else None
    generate_certificate_png(student, course, num, date, output_path=out, verify_url=url)
    print(f'PNG certificate generated: {out}')
